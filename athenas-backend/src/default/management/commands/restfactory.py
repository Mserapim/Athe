    re_app = re.compile(
        r"^(?P<app_label>([a-z]|_)+)\.(?P<model>([a-zA-Z]{1}[a-zA-Z0-9|_]+))$"
    )

    table = {}

    def create_module(self, path):
        self.create_directory(path)
        initfile = os.path.join(path, "__init__.py")
        os.path.exists(initfile) or open(initfile, "w")

    def create_directory(self, path):
        parts = path.split(os.path.sep)
        parent_dir = os.path.sep.join(parts[:-1])
        dirname = parts[-1]

        if os.path.isdir(parent_dir) is False:
            self.create_directory(parent_dir)

        if os.path.isdir(path) is False:
            os.mkdir(path)
            return True
        else:
            return False

    @classmethod
    def register(klass, field, extract):
        klass.table.update({field: extract})

    def get_namespace(self, Model, namespace=None, **kargs):
        if namespace is None:
            namespace = ".".join(Model.__module__.split(".")[:-1])
        return namespace

    def get_destination_path(self, destination, namespace):
        current_dir = os.getcwd()

        tmp = destination.replace(os.path.sep, ".")
        if namespace.startswith(tmp):
            namespace = namespace[len(tmp) + 1 :]

        return os.path.sep.join(
            [current_dir, destination, "static", namespace.replace(".", os.path.sep)]
        )

    def translate(self, Field):
        fn = self.table.get(Field.__class__, None)

        if fn is None:
            log.warn("Not found type for %s with type %s", Field.name, Field.__class__)
        else:
            log.debug([Field.__class__, fn])

        return fn if fn is not None else extractors.defaultfield

    def extract_field_config(self, Field):
        fn = self.translate(Field)

        return fn(Field)

    def extract_field(self, Model):
        rst = {}

        for field in [
            field
            for field in Model._meta.fields
            if not isinstance(field, models.AutoField)
        ]:
            rst.update(**{field.name: self.extract_field_config(field)})

        return rst

    def indent(self, text, number, indent=4, skip_indent_first_line=True):
        lines = text.split("\n")

        indented_lines = []
        for line in lines:
            if skip_indent_first_line and line == lines[0]:
                indented_lines.append(line)
            else:
                indented_lines.append("".join([(" " * (4 * number)), line]))

        return "\n".join(indented_lines)

    def rest_config(self, conf, clear_key=False):
        fields = []

        for name, value in list(conf.get("rest", {}).get("fields", {}).items()):
            fields += value.get("field", [])

        if clear_key:
            fields_ = re.sub(
                r"\"(?P<key>\w+)\"\:",
                r"\1:",
                self.indent(json.dumps(fields, indent=4), 3),
            )
        else:
            fields_ = self.indent(json.dumps(fields, indent=4), 3)

        rst = {
            "api_path": conf.get("api_path"),
            "namespace": conf.get("rest", {}).get("namespace"),
            "classname": conf.get("rest", {}).get("className"),
            "prefix": conf.get("rest", {}).get("prefix", ""),
            "fields": fields_,
        }

        return rst

    def rest_py_config(self, conf):
        rst = self.rest_config(conf)

        fields = []
        imports = []
        cases = []

        for name, field in list(conf.get("rest", {}).get("fields", {}).items()):
            form_field = field.get("form", {})
            if form_field.get("xtype", "") == "datefield":
                fields.append(
                    "%s%s=nil_date(instance.%s, None)" % ((" " * 4) * 3, name, name)
                )
                imports.append("from contrib.nil import nil_date")
                imports.append("from contrib.utils import DateUtils")
                cases.append(TEMPLATES.get("case-datefield") % {"name": name})
            elif form_field.get("xtype", "") == "rest-autocompletefield":
                fields.append(
                    "%s%s=nil_pk(instance.%s, None)" % ((" " * 4) * 3, name, name)
                )
                fields.append(
                    "%s%s_unicode=nil_unicode(instance.%s, None)"
                    % ((" " * 4) * 3, name, name)
                )
                imports.append("from contrib.nil import nil_pk, nil_unicode")
                cases.append(
                    TEMPLATES.get("case-rest-autocompletefield") % {"name": name}
                )
            elif form_field.get("xtype", "") == "checkbox":
                fields.append("%s%s=instance.%s" % ((" " * 4) * 3, name, name))
                cases.append(TEMPLATES.get("case-checkboxfield") % {"name": name})
            elif form_field.get("xtype", "") == "numberfield" and form_field.get(
                "allowDecimals", False
            ):
                fields.append(
                    "%s%s=float(instance.%s or 0)" % ((" " * 4) * 3, name, name)
                )

            elif form_field.get("xtype", "") == "numberfield" and not form_field.get(
                "allowDecimals", False
            ):
                fields.append(
                    "%s%s=int(instance.%s or 0)" % ((" " * 4) * 3, name, name)
                )
            elif form_field.get("xtype", "") == "tk-datetimefield":
                fields.append(
                    "%s%s=nil_datetime(instance.%s, None)" % ((" " * 4) * 3, name, name)
                )
                imports.append("from contrib.nil import nil_datetime")
                imports.append("from contrib.utils import DateUtils")
                cases.append(TEMPLATES.get("case-datetimefield") % {"name": name})
            elif form_field.get("xtype", "") == "combo":
                fields.append("%s%s=instance.%s" % ((" " * 4) * 3, name, name))
                fields.append(
                    "%s%s_display=nil_display(instance, '%s', None)"
                    % ((" " * 4) * 3, name, name)
                )
                imports.append("from contrib.nil import nil_display")
            else:
                fields.append("%s%s=instance.%s" % ((" " * 4) * 3, name, name))

        rst.update(
            fields=",\n".join(fields),
            imports="\n".join(set(imports)),
            cases=self.indent("\n".join(cases), 2),
        )

        return rst

    def window_config(self, conf):
        rst = self.rest_config(conf)

        rst.update(
            fields=re.sub(
                r"\"(?P<key>\w+)\"\:",
                r"\1:",
                self.indent(
                    json.dumps(
                        [
                            v.get("form", {})
                            for k, v in list(
                                conf.get("rest", {}).get("fields", {}).items()
                            )
                        ],
                        indent=4,
                    ),
                    3,
                ),
            )
        )

        return rst

    def grid_config(self, conf):
        rst = self.rest_config(conf)

        tpl = """{header: '%(fieldLabel)s', dataIndex: '%(name)s', width: 90}"""
        tpls = {
            "checkbox": """{header: '%(fieldLabel)s', dataIndex: '%(name)s_display', width: 90, renderer: function(value) { return (value ? 'SIM' : 'NÃO'); }}""",
            "combo": """{header: '%(fieldLabel)s', dataIndex: '%(name)s_display', width: 120}""",
            "rest-autocompletefield": """{header: '%(fieldLabel)s', dataIndex: '%(name)s_unicode', width: 120}""",
            "datefield": """{header: '%(fieldLabel)s', dataIndex: '%(name)s', width: 90, renderer: Ext.util.Format.dateRenderer('d/m/Y')}""",
            "tk-datetimefield": """{header: '%(fieldLabel)s', dataIndex: '%(name)s', width: 90, renderer: Ext.util.Format.dateRenderer('d/m/Y H:i')}""",
        }

        rst.update(
            column=self.indent(
                ",\n".join(
                    [
                        tpls.get(v.get("form", {}).get("xtype"), tpl)
                        % v.get("form", {})
                        for k, v in list(conf.get("rest", {}).get("fields", {}).items())
                    ]
                ),
                5,
            )
        )

        return rst

    def manage_config(self, conf):
        rst = self.rest_config(conf)

        return rst

    def get_base_filename(self, conf):
        return os.path.sep.join(
            [
                conf.get("destination"),
                conf.get("rest", {}).get("className", "Undefined"),
            ]
        )

    def builder_js_grid(self, conf, overwrite):
        filename = "%sGrid.js" % self.get_base_filename(conf)
        base_filename = None

        print("Creating JavaScript for Grid file in %s" % filename)

        if os.path.exists(filename) and not overwrite:
            base_filename = filename
            filename = "".join([base_filename, ".1"])

        with codecs.open(filename, "w", "utf-8") as filebuffer:
            tpl = TEMPLATES.get("grid")
            filebuffer.write(tpl % self.grid_config(conf))

        if base_filename:
            self.diff(base_filename, filename, base_filename)
            os.unlink(filename)

    def diff(self, base_path, new_path, out_path):
        from django.conf import settings

        diff_options = getattr(settings, "DIFF_OPTIONS", "--qall")
        diff_tool = getattr(settings, "DIFF_TOOL", "kdiff3")

        os.system(
            "%(diff_tool)s %(diff_options)s -o %(out_path)s %(base_path)s %(new_path)s"
            % vars()
        )

