    def builder(
        self,
        conf,
        without_rest,
        without_window,
        without_grid,
        nodry,
        overwrite,
        with_manager,
        **kargs
    ):
        if without_rest is False:
            self.builder_js_restful(conf, overwrite)
            self.builder_py_restful(conf, nodry, overwrite)
        if without_window is False:
            self.builder_js_window(conf, overwrite)
        if without_window is False:
            self.builder_js_grid(conf, overwrite)
        if with_manager:
            self.builder_js_manage(conf, overwrite)

    def get_module_path(self, module):
        mod = importlib.import_module(module)
        return os.path.dirname(mod.__file__)

    def extract_from_model(self, Model, namespace, destination, prefix, **kargs):
        api_path = os.path.join(
            self.get_module_path(".".join(Model.__module__.split(".")[:-1])), "api"
        )

        rst = {
            "api_path": api_path,
            "destination": self.get_destination_path(destination, namespace),
            "rest": {
                "prefix": prefix,
                "className": Model.__name__,
                "namespace": namespace,
                "fields": self.extract_field(Model),
            },
        }

        return rst

    def handle(self, model, **kargs):
        rst = self.re_app.match(model)

        if rst is not None:
            params = rst.groupdict()
            for k in params:
                params[k] = params[k].lower()
            print(params)
            try:
                ctype = ContentType.objects.get(**params)
            except ContentType.DoesNotExist:
                print("The model content type not found.")
            else:
                Model = ctype.model_class()
                kargs.update(namespace=self.get_namespace(Model, **kargs))
                conf = self.extract_from_model(Model, **kargs)

                self.create_directory(conf.get("destination"))
                self.builder(conf, **kargs)
        else:
            print("The model identification not match with xxx.")


