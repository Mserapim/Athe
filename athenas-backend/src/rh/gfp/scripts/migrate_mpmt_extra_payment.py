def migrate_extra_payments(mats):
    createds = 0
    updateds = 0
    for m in mats:
        obj, created = ExtraPaymentPeriod.objects.get_or_create(
            employee=Servidor.objects.get(matricula=m),
            extra_payment=ExtraPayment.objects.get(slug=mats[m][0]),
            value=mats[m][1],
            type_value=mats[m][2],
            start_validity=date(2021, 3, 1),
        )
        if created:
            createds += 1
        else:
            updateds += 1
    return createds, updateds


