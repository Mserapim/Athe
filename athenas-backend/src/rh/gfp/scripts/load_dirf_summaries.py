def load_summaries(calendar_year):
    set_current_user("athenas")
    # calendar_year = 2019
    codes = set([d[0] for d in drs])
    print(f"APAGANDO DirfSummary para {calendar_year}....")
    dels = dirfm.DirfSummary.objects.filter(
        calendar_year=calendar_year, code__codigo__in=codes, dirf_created=False
    ).delete()
    print(dels)
    print("")

    for d in drs:
        id_rtrt = dirfm.Choice.objects.get(
            app_label="dirf", name="IDENTIFIERS_DIRF", value=d[6]
        )
        id_rtirf = dirfm.Choice.objects.get(
            app_label="dirf", name="IDENTIFIERS_DIRF", value=d[7]
        )
        print(d[0], d[1], id_rtrt, id_rtirf)
        nr = dirfm.NaturezaRendimento.objects.get(codigo=d[0])
        person = (
            PessoaFisica.objects.filter(cpf=d[1]).first()
            if len(d[1]) == 11
            else PessoaJuridica.objects.filter(cnpj=d[1]).first()
        )
        if not person:
            if len(d[1]) == 11:
                person = PessoaFisica.objects.create(nome=d[8], cpf=d[1])
            else:
                person = PessoaJuridica.objects.create(
                    nome=d[8], cnpj=d[1], razao_social=d[8]
                )
            time.sleep(5)
            print("\033[94m%s\033[0m" % person)
        else:
            print(person)

        ds, created = dirfm.DirfSummary.objects.get_or_create(
            calendar_year=calendar_year,
            identifier=id_rtrt.value,
            person=person,
            code=nr,
            info=d[5],
        )
        if getattr(ds, "value_%02d" % d[2]):
            print("\033[91mEXIST\033[0m")
        setattr(ds, "value_%02d" % d[2], d[3])
        ds.save()
        print("\033[92m%s\033[0m" % id_rtrt.label)
        if d[4]:
            ds1, created1 = dirfm.DirfSummary.objects.get_or_create(
                calendar_year=calendar_year,
                identifier=id_rtirf.value,
                person=person,
                code=nr,
                info=d[5],
            )
            if getattr(ds1, "value_%02d" % d[2]):
                print("\033[91mEXIST\033[0m")
            setattr(ds1, "value_%02d" % d[2], d[4])
            ds1.save()
            print("\033[92m%s\033[0m" % id_rtirf.label)

        print("")
