def update_entries(regs=[]):
    color = NC

    c = 1
    a = 0
    p = Folha.objects.get(tipo_folha=101, periodo__ano=2020, periodo__mes=12)
    ups = 0
    dif_values = {}
    for reg in regs:
        q1 = p.lancamentos.filter(servidor__matricula=reg[0], evento__numero=reg[1])
        ees = q1.filter(correct_valor=f"{reg[4]:02f}")
        # print(f'{reg} > {ees.count()}/{q1.count()}')
        if ees.count() == 1:
            if str(ees.first().info) != str(reg[5]):
                ees.update(info=f"{reg[5]}", cid=int(reg[5]))
                ups += 1
                color = GREEN
                # print(f'{color}{reg}{NC} - "{ees.first().info}"{type(ees.first().info)}=="{reg[5]}"{type(f"{reg[5]}")}: {ees.first().info != f"{reg[5]}"}')
            a += 1

        elif q1.count() == 1:
            if str(q1.first().info) != str(reg[5]):
                q1.update(info=f"{reg[5]}", cid=int(reg[5]))
                ups += 1
                color

                # print(f'{color}{reg}{NC} - {q1.first().info}/{reg[5]}')
            a += 1
            dif_values[q1.first()] = reg
        else:
            color = RED if ees.count() or q1.count() else BLUE
            print(f'{c};{color}{";".join([str(r) for r in reg])}{NC}')
            # print(c, f'{color}{ees.count()}/{q1.count()}', reg)
            c += 1

    print(f"Consignações atualizadas: {a}/{ups}")
    print("")
    c = 1
    print("Consignações não atualizadas: ")
    for fe in p.lancamentos.filter(evento__consignment_manager=True):
        info = f"{fe.info}"

        if not info.isdigit():
            print(
                f"{c};{fe.servidor.matricula};{fe.evento.numero};{fe.valor};{fe.info};{fe.cid}"
            )
            c += 1
    print("")
    print(f"Consignações com valores diferentes: {len(dif_values)}")
    for fe in dif_values:
        print(
            f"{fe.servidor.matricula};{fe.evento.numero};{fe.prazo};{fe.parcela};{fe.correct_valor};{fe.cid or fe.info};{dif_values[fe][4]}"
        )


