def can_set(func, *args):
    def call(*call_args):
        situation = call_args[0]
        situations = call_args[1]
        situations_goto = args[0]
        return func(situation, situations_goto, situations)

    return call


def get_situations_goto(situation, situations_goto, situations):
    return situation in situations and situations_goto


