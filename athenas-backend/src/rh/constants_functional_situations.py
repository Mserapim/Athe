def SITUATION_APPLICABLE(situation, validity=False):
    situation_origin = {}
    if situation in ACTIVE_SITUATIONS_RAW:
        situation_origin = ACTIVE_SITUATIONS
    elif situation in DEPARTURE_SITUATIONS_RAW:
        situation_origin = DEPARTURE_SITUATIONS
    elif situation in INACTIVE_SITUATIONS_RAW:
        situation_origin = INACTIVE_SITUATIONS
    elif situation in NOT_APPLICABLE_SITUATIONS_RAW:
        situation_origin = NOT_APPLICABLE_SITUATIONS
    applicable = situation_origin.get(situation, False) and situation_origin.get(
        situation
    )(situation, situation_origin)
    applicable = (
        False
        if isinstance(applicable, (dict, list)) and len(applicable) == 0
        else applicable
    )
    return applicable


